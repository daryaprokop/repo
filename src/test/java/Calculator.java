public class Calculator {

    public static int sum(int a, int b) {
        return a+b;
    }
    public static int subtract(int a, int b) { // вычитание
        return a-b;
    }

    public static int multiply (int a, int b) { // умножение
        return a*b;
    }
    public static int divide (int a, int b){ // деление
        return a/b;
    }

    public static double average (double a, double b) { // среднее арифметическое
        return (a+b)/2;
    }
}
